def count_images(folder):
    extensions = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff"}

    results = {}

    for class_dir in sorted(folder.iterdir()):
        if class_dir.is_dir():
            count = sum(
                1 for f in class_dir.rglob("*")
                if f.suffix.lower() in extensions
            )
            results[class_dir.name] = count

    return results


