import torch
import torch.nn.functional as F
import numpy as np
from PIL import Image
import matplotlib.pyplot as plt


class GradCAM:

    def __init__(self, model):

        self.model = model

        self.activations = None
        self.gradients = None

        self.target_layer = None

        # ----------------------------------------------------
        # Find last convolutional layer automatically
        # ----------------------------------------------------

        for module in reversed(
            list(model.modules())
        ):

            if isinstance(
                module,
                torch.nn.Conv2d
            ):

                self.target_layer = module
                break

        if self.target_layer is None:

            raise RuntimeError(
                "No convolutional layer found."
            )

        # ----------------------------------------------------
        # Hooks
        # ----------------------------------------------------

        self.target_layer.register_forward_hook(
            self.forward_hook
        )

        self.target_layer.register_full_backward_hook(
            self.backward_hook
        )

        print(
            "Grad-CAM target layer:",
            self.target_layer
        )


    def forward_hook(
        self,
        module,
        input,
        output
    ):

        self.activations = output


    def backward_hook(
        self,
        module,
        grad_input,
        grad_output
    ):

        self.gradients = grad_output[0]


    def generate(
        self,
        tensor,
        class_index
    ):

        self.model.zero_grad()

        output = self.model(tensor)

        score = output[
            0,
            class_index
        ]

        score.backward()

        gradients = self.gradients
        activations = self.activations

        # ----------------------------------------------------
        # Global average pooling
        # ----------------------------------------------------

        weights = gradients.mean(
            dim=(2, 3),
            keepdim=True
        )

        cam = (
            weights * activations
        ).sum(
            dim=1,
            keepdim=True
        )

        cam = F.relu(cam)

        cam = F.interpolate(
            cam,
            size=(
                IMAGE_SIZE,
                IMAGE_SIZE
            ),
            mode="bilinear",
            align_corners=False
        )

        cam = cam[0, 0]

        cam -= cam.min()

        cam /= (
            cam.max() + 1e-8
        )

        return cam.detach().cpu().numpy()


